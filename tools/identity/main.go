// Identity is the hand-edited source. Every identifier below is derived from
// it so a fork changes one prefix, one team and one repository.
type Identity struct {
	Product           string   `json:"product"`
	BundlePrefix      string   `json:"bundle_prefix"`
	AppleTeamID       string   `json:"apple_team_id"`
	Repository        string   `json:"repository"`
	DefaultGateway    string   `json:"default_gateway"`
	HomebrewTap       string   `json:"homebrew_tap"`
	ContainerRegistry string   `json:"container_registry"`
	TestFlightGroups  []string `json:"testflight_groups"`
}

// Derived is what templates read.
type Derived struct {
	Identity
	MacBundleID          string
	IOSBundleID          string
	IOSShareBundleID     string
	IOSAppGroup          string
	IOSE2EBundleID       string
	AndroidApplicationID string
	DaemonIdentifier     string
	CaptureIdentifier    string
	PrivacyIdentifier    string
	PrivacySocketPath    string
	DefaultGatewayURL    string
	ReleasesURL          string
	ReleaseSigner        string
	ReleaseSignerPattern string
	MacURLScheme         string
	IOSURLScheme         string
	AndroidURLScheme     string
	LatestReleaseAPIURL  string
	MacKeychainService   string
	IOSKeychainService   string
	FixturePasteboard    string
}

// ReleaseWorkflow is the only workflow that signs release checksums. Installed
// updaters verify this exact identity, so renaming it is a protocol break.
const ReleaseWorkflow = ".github/workflows/release.yml"

func derive(identity Identity) (Derived, error) {
	if !regexp.MustCompile(`^[a-z][a-z0-9]*(\.[a-z][a-z0-9]*)+$`).MatchString(identity.BundlePrefix) {
		return Derived{}, fmt.Errorf("bundle_prefix %q must be a lowercase reverse-DNS prefix", identity.BundlePrefix)
	}
	if !regexp.MustCompile(`^[A-Z0-9]{10}$`).MatchString(identity.AppleTeamID) {
		return Derived{}, fmt.Errorf("apple_team_id %q must be a 10-character Apple team ID", identity.AppleTeamID)
	}
	if !regexp.MustCompile(`^[A-Za-z0-9-]+/[A-Za-z0-9._-]+$`).MatchString(identity.Repository) {
		return Derived{}, fmt.Errorf("repository %q must be OWNER/NAME", identity.Repository)
	}
	if identity.Product == "" || identity.DefaultGateway == "" || strings.Contains(identity.DefaultGateway, "/") {
		return Derived{}, fmt.Errorf("product and default_gateway (a host name) are required")
	}
	prefix := identity.BundlePrefix
	return Derived{
		Identity:             identity,
		MacBundleID:          prefix + ".mac",
		IOSBundleID:          prefix + ".ios",
		IOSShareBundleID:     prefix + ".ios.share",
		IOSAppGroup:          "group." + prefix + ".ios",
		IOSE2EBundleID:       prefix + ".ios.e2e",
		AndroidApplicationID: prefix + ".android",
		DaemonIdentifier:     prefix + ".daemon",
		CaptureIdentifier:    prefix + ".capture",
		PrivacyIdentifier:    prefix + ".privacy",
		PrivacySocketPath:    "/var/run/" + prefix + ".privacy.sock",
		DefaultGatewayURL:    "https://" + identity.DefaultGateway,
		ReleasesURL:          "https://github.com/" + identity.Repository + "/releases",
		ReleaseSigner:        "https://github.com/" + identity.Repository + "/" + ReleaseWorkflow + "@refs/heads/main",
		ReleaseSignerPattern: "^" + regexp.QuoteMeta("https://github.com/"+identity.Repository+"/"+ReleaseWorkflow+"@refs/heads/main") + "$",
		MacURLScheme:         "dieter-mac",
		IOSURLScheme:         "dieter-ios",
		AndroidURLScheme:     "dieter-android",
		LatestReleaseAPIURL:  "https://api.github.com/repos/" + identity.Repository + "/releases/latest",
		MacKeychainService:   prefix + ".mac",
		IOSKeychainService:   prefix + ".ios.core",
		FixturePasteboard:    prefix + ".fixture.",
	}, nil
}

