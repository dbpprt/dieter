func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "fail when a generated file differs instead of writing it")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, "identity:", err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	raw, err := os.ReadFile(filepath.Join(root, "config", "identity.json"))
	if err != nil {
		return err
	}
	var identity Identity
	decoder := json.NewDecoder(bytes.NewReader(raw))
	if err := decoder.Decode(&identity); err != nil {
		return fmt.Errorf("config/identity.json: %w", err)
	}
	derived, err := derive(identity)
	if err != nil {
		return fmt.Errorf("config/identity.json: %w", err)
	}
	var stale []string
	for _, out := range outputs {
		rendered, err := render(root, out, derived)
		if err != nil {
			return fmt.Errorf("%s: %w", out.path, err)
		}
		path := filepath.Join(root, out.path)
		current, _ := os.ReadFile(path)
		if bytes.Equal(current, rendered) {
			if out.mode == 0 {
				continue
			}
			if info, err := os.Stat(path); err == nil && info.Mode().Perm() == out.mode {
				continue
			}
		}
		if check {
			stale = append(stale, out.path)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		mode := out.mode
		if mode == 0 {
			mode = 0o644
		}
		if err := os.WriteFile(path, rendered, mode); err != nil {
			return err
		}
		if err := os.Chmod(path, mode); err != nil {
			return err
		}
	}
	if len(stale) > 0 {
		return fmt.Errorf("stale generated identity files (run `just generate`): %s", strings.Join(stale, ", "))
	}
	return nil
}

func render(root string, out output, derived Derived) ([]byte, error) {
	text := out.template
	if out.source != "" {
		raw, err := os.ReadFile(filepath.Join(root, out.source))
		if err != nil {
			return nil, err
		}
		text = string(raw)
	}
	tmpl, err := template.New(out.path).Funcs(template.FuncMap{
		"header": func() string { return header },
		"join":   strings.Join,
		// brewTap turns OWNER/homebrew-NAME into the `brew` short form OWNER/NAME.
		"brewTap": func(tap string) string {
			owner, name, _ := strings.Cut(tap, "/")
			return owner + "/" + strings.TrimPrefix(name, "homebrew-")
		},
	}).Parse(text)
	if err != nil {
		return nil, err
	}
	var buffer bytes.Buffer
	if err := tmpl.Execute(&buffer, derived); err != nil {
		return nil, err
	}
	return buffer.Bytes(), nil
}
